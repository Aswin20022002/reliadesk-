"""Builds lib/imsData.ts from the NASA IMS bearing run-to-failure dataset (real accelerometer records).

Source of the features used here: https://github.com/fatemeh-studio/nasa-bearing-anomaly (MIT licence),
data/processed/test{1,2,3}_raw.csv, which are RMS features computed from the original IMS 20 kHz records.
Original data: J. Lee, H. Qiu, G. Yu, J. Lin, Rexnord Technical Services (2007). IMS, University of Cincinnati.
"Bearing Data Set", NASA Prognostics Data Repository, NASA Ames Research Center.

Usage:
  git clone --depth 1 https://github.com/fatemeh-studio/nasa-bearing-anomaly.git
  IMS_REPO=./nasa-bearing-anomaly python3 scripts/build_ims_data.py
"""
import os, json
import numpy as np
import pandas as pd

REPO = os.environ.get("IMS_REPO", "./nasa-bearing-anomaly")
P = os.path.join(REPO, "data", "processed")
CURVE_HOURS = 168


def load(t, b):
    d = pd.read_csv(os.path.join(P, f"test{t}_raw.csv"))
    d["ts"] = pd.to_datetime(d["timestamp"])
    cols = [f"Bearing{b}_ch{c}_rms" for c in ((1, 2) if t == 1 else (1,))]
    x = d[cols].max(axis=1).values
    return d["ts"], x


# Run-to-failure bearings with a documented failure (IMS readme): Set 1 B3 inner race, Set 1 B4 roller element,
# Set 2 B1 outer race, Set 3 B3 outer race.
FAILED = {
    "IMS Set 1, bearing 3 (inner race failure)": (1, 3),
    "IMS Set 2, bearing 1 (outer race failure)": (2, 1),
    "IMS Set 3, bearing 3 (outer race failure)": (3, 3),
    "IMS Set 1, bearing 4 (roller element failure)": (1, 4),
}
curves = []
for name, (t, b) in FAILED.items():
    ts, x = load(t, b)
    base = float(np.median(x[: len(x) // 4]))
    n = len(x)
    while n > 0 and x[n - 1] < 0.5 * base:  # the last file(s) are recorded after shutdown
        n -= 1
    x, ts = x[:n], ts.iloc[:n]
    hrs = ((ts - ts.iloc[-1]).dt.total_seconds() / 3600).values
    vals = []
    for k in range(CURVE_HOURS - 1, -1, -1):  # oldest to newest, one raw snapshot per hour
        i = int(np.argmin(np.abs(hrs + k)))
        vals.append(round(float(x[i] / base), 3))
    curves.append({"source": name, "baselineG": round(base, 3), "ratio": vals})

# Healthy bearings (no failure in the run) give real measurement noise: relative deviation from a rolling median.
HEALTHY = [(2, 2), (2, 3), (2, 4), (1, 1), (1, 2), (3, 1), (3, 2)]
noise = []
for t, b in HEALTHY:
    _, x = load(t, b)
    x = x[: int(len(x) * 0.6)][::6][:150]
    med = pd.Series(x).rolling(24, center=True, min_periods=6).median().values
    noise += [round(float(v), 4) for v in (x / med - 1)]

out = {
    "citation": "J. Lee, H. Qiu, G. Yu, J. Lin, Rexnord Technical Services (2007). IMS, University of Cincinnati. Bearing Data Set, NASA Prognostics Data Repository, NASA Ames Research Center.",
    "featureSource": "github.com/fatemeh-studio/nasa-bearing-anomaly (MIT), data/processed/test{1,2,3}_raw.csv",
    "curves": curves,
    "noise": noise,
}
ts = "// Generated by scripts/build_ims_data.py from the NASA IMS bearing run-to-failure dataset. Do not edit by hand.\n"
ts += "export const IMS = " + json.dumps(out) + " as const\n"
open("lib/imsData.ts", "w").write(ts)
print("curves", [(c["source"], max(c["ratio"])) for c in curves], "noise n", len(noise), "std %.4f" % float(np.std(noise)))
